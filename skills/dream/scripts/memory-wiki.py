#!/usr/bin/env python3
"""Render the dev wiki from project memory instead of authoring it separately.

Why this exists
---------------
The wiki was a third hand-written copy of each project's state, alongside the
global memory and the per-project memory scope. Three writers meant drift: the
organizer updated the wiki and memory in the same run, and nothing checked that
they agreed.

Now each project memory scope carries a curated INDEX (regenerated by
`dream.sh reindex`), and the wiki page is a rendering of that INDEX. A derived
page cannot contradict its source, and generating it costs no model call.

Human edits survive: anything under a `## Notes` heading is carried over
verbatim. On first generation, an existing page's body is preserved under
`## Notes (carried over)` so no wording is lost; prune it once you have read it.

Usage:
  memory-wiki.py [--memory-dir DIR] [--dry-run]
"""
from __future__ import annotations

import argparse
import os
import pathlib
import re
import sys

INDEX_START = "<!-- INDEX START"
INDEX_END = "<!-- INDEX END -->"
LEGACY_START = "<!-- INDEX -->"
LEGACY_END = "<!-- /INDEX -->"
NOTES_HEADING = "## Notes"
CARRIED_HEADING = "## Notes (carried over)"

FRONTMATTER = """---
origin: generated
source: {source}
generated_at: {date}
type: pi-wiki
maintained-by: dream-pass
sensitivity: internal
---
"""


def index_body(text: str) -> str | None:
    """Return the INDEX text of a memory file, or None when it has none."""
    for start, end in ((INDEX_START, INDEX_END), (LEGACY_START, LEGACY_END)):
        i = text.find(start)
        if i < 0:
            continue
        line_end = text.find("\n", i)
        if line_end < 0:
            continue
        j = text.find(end, line_end)
        if j < 0:
            continue
        return text[line_end + 1 : j].strip("\n")
    return None


def notes_section(text: str) -> str:
    """Everything from a `## Notes` heading to the end, verbatim."""
    match = re.search(r"^## Notes\s*$", text, re.MULTILINE)
    if not match:
        return ""
    return text[match.start() :].rstrip() + "\n"


def strip_frontmatter(text: str) -> str:
    if text.startswith("---\n"):
        end = text.find("\n---\n", 4)
        if end >= 0:
            return text[end + 5 :]
    return text


def slug_for(key: str) -> str:
    """project-atom-f228a88b205e -> project-atom (the extension's key format)."""
    match = re.match(r"^(.*)-[0-9a-f]{12}$", key)
    return match.group(1) if match else key


def render(key: str, body: str, notes: str, source: str, date: str) -> str:
    parts = [FRONTMATTER.format(source=source, date=date), f"# {slug_for(key)}\n", body.rstrip() + "\n"]
    if notes:
        parts.append("\n" + notes.rstrip() + "\n")
    return "\n".join(parts)


def main(argv: list[str]) -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--memory-dir", type=pathlib.Path)
    parser.add_argument("--dry-run", action="store_true")
    args = parser.parse_args(argv)

    mem = args.memory_dir or pathlib.Path(
        os.environ.get("PI_MEMORY_DIR") or pathlib.Path.home() / ".pi" / "agent" / "memory"
    )
    wiki = mem / "wiki"
    projects = sorted((mem / "projects").glob("*/MEMORY.md")) if (mem / "projects").is_dir() else []
    if not projects:
        print("memory-wiki: no project memory scopes found", file=sys.stderr)
        return 1

    date = __import__("datetime").date.today().isoformat()
    written, carried, skipped = 0, 0, 0
    listing: list[tuple[str, str]] = []

    # Two scopes can share a label (two checkouts of the same project), so a
    # colliding slug falls back to the full key instead of overwriting a page.
    slugs = [slug_for(p.parent.name) for p in projects]
    collisions = {s for s in slugs if slugs.count(s) > 1}

    for path in projects:
        key = path.parent.name
        slug = key if slug_for(key) in collisions else slug_for(key)
        text = path.read_text()
        body = index_body(text)
        if body is None:
            print(f"memory-wiki: skipped {key} (no INDEX; run dream.sh reindex)", file=sys.stderr)
            skipped += 1
            continue

        target = wiki / f"{slug}.md"
        notes = ""
        if target.is_file():
            raw = target.read_text()
            existing = strip_frontmatter(raw)
            notes = notes_section(existing)
            # Only an authored page gets its body preserved. A page this script
            # already generated must never be folded into its own notes, or each
            # run would duplicate the content.
            if not notes and "origin: generated" not in raw.split("---", 2)[1]:
                notes = f"{CARRIED_HEADING}\n\n{existing.strip()}\n"
                carried += 1

        rendered = render(key, body, notes, f"projects/{key}/MEMORY.md", date)
        listing.append((slug, body.splitlines()[0] if body else slug))
        if args.dry_run:
            print(f"memory-wiki: would write {target.relative_to(mem)}")
        else:
            target.write_text(rendered)
        written += 1

    rendered_slugs = {slug for slug, _ in listing}
    authored = sorted(
        p.stem for p in wiki.glob("*.md")
        if p.stem not in rendered_slugs and p.stem != "README"
    )

    # An index page so the folder is browsable in any Markdown viewer.
    index_lines = ["---", "origin: generated", f"generated_at: {date}", "type: pi-wiki", "---", "", "# Dev wiki", ""]
    index_lines.append("Generated from each project's memory INDEX. Edit the memory, not this page.")
    index_lines.append("")
    index_lines.append("## Generated from project memory")
    index_lines.append("")
    for slug, _ in sorted(listing):
        index_lines.append(f"- [[{slug}]]")
    if authored:
        index_lines.append("")
        index_lines.append("## Authored (no project memory scope)")
        index_lines.append("")
        index_lines.append("These pages have no matching `projects/<key>/MEMORY.md`, so nothing")
        index_lines.append("regenerates them. Give the project a memory scope, or fold the page")
        index_lines.append("into memory and delete it.")
        index_lines.append("")
        for slug in authored:
            index_lines.append(f"- [[{slug}]]")
    index_text = "\n".join(index_lines) + "\n"
    if not args.dry_run:
        (wiki / "README.md").write_text(index_text)

    print(f"memory-wiki: {written} page(s) rendered, {carried} carried over, {skipped} skipped")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
